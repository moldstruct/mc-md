#!/bin/bash
#
# Regression test for the MolDStruct MC/MD ionization module.
#
# Runs the shipped lysozyme example for a few hundred steps with the Monte
# Carlo seed pinned, in two cases, both with the built-in atomic data (the
# default, mcmd-atomic-data = hydrogenic; no Atomic_data directory):
#
#   none  no electron cloud (mcmd-electrons = none, mcmd-collisions = 0): the
#         original MolDStruct model, photoionization, Auger, fluorescence and
#         charge transfer only
#   full  the full model at its defaults: the Poisson-Boltzmann electron cloud
#         (mcmd-electrons = pbgrid) with electron-impact ionization from the
#         built-in Lotz formula (mcmd-collisions = 1, mcmd-coll-data = lotz),
#         on a coarse grid (mcmd-pb-cells-per-smoothing = 1, default 2.5): the
#         test covers the code paths, not the physics, and the 300 steps sit at
#         the pulse peak where the cloud forms and the solver works hardest
#         (~2 min per run at the default grid, a few seconds coarse)
#
# and checks, for each case,
#
#   1. the event counts match a stored reference exactly (test/reference_<case>_<steps>.txt:
#      Auger, fluorescence, photoionization, charge transfer, collisional
#      ionization, three-body recombination)
#   2. net charge is conserved: sum(charges) == photoionizations + Auger
#      + collisional ionizations - three-body recombinations
#
# and, once, with mcmd-atomic-data = files on the tables the full case wrote to
# simulation_output/Atomic_data,
#
#   3. the built-in data are what the run writes: the full case with
#      mcmd-atomic-data = files on those tables gives an identical
#      transitions.bin
#   4. a run without -ionize writes no ionization output at all
#   5. total_energies_X.txt is required when charge transfer or collisions
#      are on, and not required when both are off
#   6. statistical_weight_X.txt is optional: without it the weights are
#      computed (C(2,K) C(8,L) C(18,M)) and the run is identical
#
# (1) is a bitwise check and is the point of the test: the module is
# stochastic, but with mcmd-seed set it is deterministic, so any change
# that alters the physics moves these numbers. It is only meaningful against a
# reference generated by the same build on the same machine - a different
# compiler or optimisation level can shift the trajectory. Regenerate with
# --update when you change the physics deliberately, and say so in the commit.
#
# (2) holds regardless of build: every electron removed from an atom is a
# photoionization, an Auger event or an electron-impact ionization, one put
# back is a three-body recombination, and charge transfer only moves charge
# between atoms. A failure here is a real bug, not a platform difference.
#
# (5) guards a failure mode that used to be silent: without total energies the
# module could only score an acceptor's outermost shell, which refuses anything
# holding an inner-shell hole and suppresses charge transfer heavily while
# still producing plausible numbers. It must now stop instead.
#
# Usage:
#   test/regression.sh [--bindir DIR] [--steps N] [--update] [--keep]
#   (--update rewrites both references)
#
set -u

REPO="$(cd "$(dirname "$0")/.." && pwd)"
BINDIR="$REPO/gromacs-4.5.4-MCMD/build/src/kernel"
STEPS=300
UPDATE=0
KEEP=0
SEED=12345

while [ $# -gt 0 ]; do
    case "$1" in
        --bindir) BINDIR="$2"; shift 2 ;;
        --steps)  STEPS="$2";  shift 2 ;;
        --update) UPDATE=1;    shift ;;
        --keep)   KEEP=1;      shift ;;
        -h|--help) sed -n '2,50p' "$0"; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 2 ;;
    esac
done

WORK="$(mktemp -d)"
trap '[ "$KEEP" = 1 ] && echo "kept $WORK" || rm -rf "$WORK"' EXIT

for exe in pdb2gmx grompp mdrun; do
    if [ ! -x "$BINDIR/$exe" ]; then
        echo "FAIL: $exe not found in $BINDIR (pass --bindir)" >&2
        exit 2
    fi
done

export GMXLIB="${GMXLIB:-$REPO/gromacs-4.5.4-MCMD/share/top}"

cp "$REPO/example/1aki.pdb" "$REPO/example/exp.mdp" "$WORK/"
cd "$WORK" || exit 2

echo "workdir  $WORK"
echo "binaries $BINDIR"
echo "steps    $STEPS, seed $SEED"
echo

run() { if ! "$@" >>"$WORK/setup.log" 2>&1; then echo "FAIL: $1 failed, see $WORK/setup.log" >&2; KEEP=1; exit 1; fi; }

# -water none: the example runs in vacuum, and without the flag pdb2gmx
# prompts for a water model, which would hang an unattended run.
run "$BINDIR/pdb2gmx" -f 1aki.pdb -ff charmm27 -water none
# the seed is an mdp option since tpr version 78 (GMX_MCMD_SEED is refused)
sed -e "s/^nsteps.*/nsteps = $STEPS/" -e "s/^mcmd-autostop  *=.*/mcmd-autostop = 0/" \
    -e "/^mcmd-seed/d" -e "/^mcmd-electrons/d" -e "/^mcmd-collisions/d" -e "/^mcmd-coll-data/d" \
    -e "/^mcmd-atomic-data/d" exp.mdp > base.mdp
echo "mcmd-seed = $SEED" >> base.mdp

FAILED=0

# one case: its own directory, mdp = base.mdp + the case's lines; checks 1 and 2
run_case() {
    local name="$1" lines="$2" ref="$REPO/test/reference_${1}_${STEPS}.txt"
    mkdir -p "$WORK/$name" && cd "$WORK/$name" || exit 2
    { cat "$WORK/base.mdp"; printf "%b\n" "$lines"; } > run.mdp
    run "$BINDIR/grompp" -f run.mdp -c "$WORK/conf.gro" -p "$WORK/topol.top" -o run.tpr -po out.mdp -maxwarn 30
    if ! "$BINDIR/mdrun" -deffnm run -s run.tpr -nt 1 -ionize >mdrun.log 2>&1; then
        echo "FAIL: mdrun failed, see $WORK/$name/mdrun.log" >&2; KEEP=1; exit 1
    fi

    set -- $(tail -1 simulation_output/procces_statistics.txt)
    local AUGER=$1 FLUOR=$2 PHOTO=$3 CT=$4
    # electron-impact ionizations and three-body recombinations from mdrun's
    # end-of-run summary (collisional_log.txt is written before each step's
    # Monte Carlo and misses the last step's events); none without collisions
    set -- $(sed -n 's/^mcionize: collisional: \([0-9]*\) ionizations, \([0-9]*\) three-body.*/\1 \2/p' mdrun.log | tail -1)
    [ $# -eq 2 ] || set -- 0 0
    local COLL_ION=$1 COLL_REC=$2
    local STATS="$AUGER $FLUOR $PHOTO $CT $COLL_ION $COLL_REC"
    local CHARGE_SUM EXPECT
    CHARGE_SUM="$(awk '{s+=$2} END{print s+0}' simulation_output/charges.txt)"
    EXPECT=$((PHOTO + AUGER + COLL_ION - COLL_REC))

    echo "=== case $name"
    echo "--- 1. event counts (Auger fluorescence photoionization charge-transfer collisional-ionization recombination)"
    if [ "$UPDATE" = 1 ]; then
        echo "$STATS" > "$ref"
        echo "    wrote reference: $ref"
        echo "    $STATS"
    elif [ ! -f "$ref" ]; then
        echo "    SKIP: no reference at $ref (create it with --update)"
    elif [ "$STATS" = "$(cat "$ref")" ]; then
        echo "    PASS  $STATS"
    else
        echo "    FAIL  got      $STATS"
        echo "          expected $(cat "$ref")"
        FAILED=1
    fi

    echo "--- 2. charge conservation"
    if [ "$CHARGE_SUM" = "$EXPECT" ]; then
        echo "    PASS  sum(charges) = $CHARGE_SUM = photoionization($PHOTO) + Auger($AUGER) + collisional($COLL_ION) - recombination($COLL_REC)"
    else
        echo "    FAIL  sum(charges) = $CHARGE_SUM, expected $EXPECT"
        FAILED=1
    fi
    echo
}

run_case none "mcmd-electrons = none\nmcmd-collisions = 0"
run_case full "mcmd-electrons = pbgrid\nmcmd-collisions = 1\nmcmd-coll-data = lotz\nmcmd-pb-cells-per-smoothing = 1"

# checks 3-6 with mcmd-atomic-data = files, on the tables the full case wrote
echo "=== once, with mcmd-atomic-data = files on the tables of case full"
mkdir -p "$WORK/files" && cd "$WORK/files" || exit 2
cp -r "$WORK/full/simulation_output/Atomic_data" Atomic_data
{ cat "$WORK/full/run.mdp"; echo "mcmd-atomic-data = files"; } > run.mdp
run "$BINDIR/grompp" -f run.mdp -c "$WORK/conf.gro" -p "$WORK/topol.top" -o run.tpr -po out.mdp -maxwarn 30
REF_TRN="$WORK/full/simulation_output/transitions.bin"

echo "--- 3. built-in data = the files the run writes"
if ! "$BINDIR/mdrun" -deffnm run -s run.tpr -nt 1 -ionize >mdrun.log 2>&1; then
    echo "    FAIL  mdrun with the written files failed, see $WORK/files/mdrun.log"
    FAILED=1
elif cmp -s simulation_output/transitions.bin "$REF_TRN"; then
    echo "    PASS  transitions.bin identical"
else
    echo "    FAIL  transitions.bin differs between the built-in data and the files written from them"
    FAILED=1
fi

echo "--- 4. no -ionize writes no ionization output"
rm -rf simulation_output
run "$BINDIR/mdrun" -deffnm plain -s run.tpr -nt 1
if [ -d simulation_output ]; then
    echo "    FAIL  simulation_output/ was created without -ionize"
    FAILED=1
else
    echo "    PASS"
fi

echo "--- 5. total_energies_X.txt required only when charge transfer or collisions are on"
mkdir -p saved_total
mv Atomic_data/total_energies_*.txt saved_total/
rm -rf simulation_output
if "$BINDIR/mdrun" -deffnm notot -s run.tpr -nt 1 -ionize >notot.log 2>&1; then
    echo "    FAIL  ran without total_energies_X.txt instead of stopping"
    FAILED=1
elif grep -q total_energies notot.log; then
    echo "    PASS  charge transfer and collisions on: refused, naming the missing file"
else
    echo "    FAIL  stopped, but not with a total_energies error:"
    sed -n '/Fatal error/,+2p' notot.log | sed 's/^/          /'
    FAILED=1
fi

# without the electron cloud (collisions need it; the cloud itself reads no total energies)
sed -e "s/^mcmd-charge-transfer  *=.*/mcmd-charge-transfer = 0/" -e "/^mcmd-collisions/d" -e "/^mcmd-electrons/d" \
    run.mdp > noct.mdp
printf "mcmd-collisions = 0\nmcmd-electrons = none\n" >> noct.mdp
run "$BINDIR/grompp" -f noct.mdp -c "$WORK/conf.gro" -p "$WORK/topol.top" -o noct.tpr -po noct.out.mdp -maxwarn 30
rm -rf simulation_output
if "$BINDIR/mdrun" -deffnm noct -s noct.tpr -nt 1 -ionize >noct.log 2>&1; then
    echo "    PASS  charge transfer and collisions off: runs without it"
else
    echo "    FAIL  charge transfer and collisions off: refused, though the file is unused"
    KEEP=1
    FAILED=1
fi
mv saved_total/total_energies_*.txt Atomic_data/

echo "--- 6. statistical_weight_X.txt optional (computed weights, identical run)"
mkdir -p saved_weight
mv Atomic_data/statistical_weight_*.txt saved_weight/
rm -rf simulation_output
if ! "$BINDIR/mdrun" -deffnm noweight -s run.tpr -nt 1 -ionize >noweight.log 2>&1; then
    echo "    FAIL  refused to run without statistical_weight_X.txt"
    FAILED=1
elif cmp -s simulation_output/transitions.bin "$REF_TRN"; then
    echo "    PASS  transitions.bin identical to the run with the files"
else
    echo "    FAIL  transitions.bin differs from the run with the weight files"
    FAILED=1
fi
mv saved_weight/statistical_weight_*.txt Atomic_data/

echo
if [ "$FAILED" = 0 ]; then echo "OK"; else echo "FAILURES"; KEEP=1; fi
exit $FAILED
